# Publishes a new version of Study Buddy to GitHub. Everyone's launcher installs it the next time they open the app.
#
# First time (after creating an EMPTY, PUBLIC repository on github.com):
#   powershell -ExecutionPolicy Bypass -File publish-update.ps1 -Repo yourname/study-buddy
# Every update after that:
#   powershell -ExecutionPolicy Bypass -File publish-update.ps1 -Notes "Added dark mode"
# Options:
#   -Version 1.3.0   pick the version number (default: next patch number, e.g. 1.0.4 -> 1.0.5)
#   -Launcher        also ship a rebuilt launcher (only needed after editing launcher\Launcher.cs)
#   -NoPush          prepare and commit, but don't upload yet

param(
  [string]$Version,
  [string]$Notes = '',
  [string]$Repo,
  [switch]$Launcher,
  [switch]$NoPush
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $root
$utf8 = New-Object System.Text.UTF8Encoding $false
function Save-Text($path, $text) { [IO.File]::WriteAllText((Join-Path $root $path), $text, $utf8) }
function Invoke-Git { & git.exe @args; if ($LASTEXITCODE -ne 0) { throw "git $($args -join " ") failed." } }

if (-not (Get-Command git -ErrorAction SilentlyContinue)) { throw 'Git is not installed. Get it from https://git-scm.com' }
# Never ship scripts that clash with each other (the app would break for everyone).
& (Join-Path $root 'check-scripts.ps1')

$v = Get-Content (Join-Path $root 'version.json') -Raw | ConvertFrom-Json
$u = Get-Content (Join-Path $root 'update.json') -Raw | ConvertFrom-Json
if ($Repo) {
  $Repo = $Repo -replace '^https://github\.com/', '' -replace '\.git$', '' -replace '/$', ''
  if ($Repo -notmatch '^[\w.-]+/[\w.-]+$') { throw "-Repo should look like yourname/study-buddy" }
  $u.repo = $Repo
}
if (-not $u.repo) { throw "First create an empty public repository on github.com, then run: publish-update.ps1 -Repo yourname/study-buddy" }
if (-not $u.branch) { $u.branch = 'main' }
$firstRelease = -not (Test-Path (Join-Path $root '.git'))

# Version number
if (-not $Version) {
  if ($firstRelease) { $Version = $v.version }
  else { $p = $v.version.Split('.'); $Version = '{0}.{1}.{2}' -f $p[0], $p[1], ([int]$p[2] + 1) }
}
if ($Version -notmatch '^\d+\.\d+\.\d+$') { throw 'The version must look like 1.2.0' }
if (-not $firstRelease -and -not $Notes) { Write-Host 'Tip: add -Notes "what changed" so people see it after updating.' }
$v.version = $Version
$v.date = Get-Date -Format 'yyyy-MM-dd'
if ($Notes -or -not $firstRelease) { $v.notes = $Notes }
if ($Launcher) { $v.launcher = $Version }

Save-Text 'version.json' ($v | ConvertTo-Json)
Save-Text 'update.json' ($u | ConvertTo-Json)
Save-Text 'js\version.js' (@(
  '/* Generated by publish-update.ps1 from version.json and update.json. */',
  "const APP_VERSION = $($v.version | ConvertTo-Json);",
  "const APP_NOTES = $([string]$v.notes | ConvertTo-Json);",
  "const UPDATE_REPO = $($u.repo | ConvertTo-Json);",
  "const UPDATE_BRANCH = $($u.branch | ConvertTo-Json);"
) -join "`n")

# Build the launcher (if asked or missing) and the export folder for new friends.
if ($Launcher -or -not (Test-Path (Join-Path $root 'launcher\Study Buddy.exe'))) { & (Join-Path $root 'build-launcher.ps1') }
& (Join-Path $root 'build-export.ps1')

# Commit and upload.
if ($firstRelease) {
  Invoke-Git init
  Invoke-Git symbolic-ref HEAD "refs/heads/$($u.branch)"
  Invoke-Git remote add origin "https://github.com/$($u.repo).git"
}
if (-not ((git.exe config user.name) -or $env:GIT_AUTHOR_NAME)) { throw 'Git needs your name first: git config --global user.name "Your Name"' }
if (-not ((git.exe config user.email) -or $env:GIT_AUTHOR_EMAIL)) { throw 'Git needs your email first: git config --global user.email "you@example.com"' }
Invoke-Git add -A
Invoke-Git commit -m "Release v$Version$(if ($Notes) { ": $Notes" })"
if ($NoPush) { Write-Host "Version $Version is committed. Upload it with: git push -u origin $($u.branch)"; return }
Write-Host 'Uploading to GitHub (a browser window may ask you to sign in the first time)...'
Invoke-Git push -u origin $u.branch
Write-Host ""
Write-Host "Published Study Buddy $Version to https://github.com/$($u.repo)"
Write-Host "Everyone gets it the next time they open Study Buddy. New friends: send them export\Study Buddy (Windows).zip"
